"""Read-only v1.4.0 import receipt audit for reporting release review.

Does not touch Firestore until audit_firestore_v140() is explicitly invoked.
Does not mutate or emit invoice/customer data. A matching row COUNT is never
treated as enough to certify the identity of a nonempty report snapshot.
"""
from collections import Counter
import re

_RECEIPT_ID = re.compile(r"[a-f0-9]{32}\Z")
_NONAPPLIED = frozenset(("STAGING", "STAGING_FAILED", "PREVIEW_READY"))
_FINAL = "COMPLETED"


def audit_import_receipts(receipts, imported_rows, report_manifest):
    """Return a non-sensitive release gate receipt from explicit input evidence.

    receipts is a list of (receipt_id, dict) pairs from the *entire*
    dashboard_import_receipts_v140 collection, not only receipts referenced
    by rows. imported_rows must be generated by completed_import_rows(db).
    Unknown, inconsistent, in-progress or orphaned states fail closed.
    """
    blockers = []
    seen = set()
    accepted = {}
    statuses = Counter()
    report_count = report_manifest.get("completed_import_rows") if isinstance(
        report_manifest, dict
    ) else None

    def block(reason):
        if reason not in blockers:
            blockers.append(reason)

    for item in receipts:
        if not isinstance(item, (tuple, list)) or len(item) != 2:
            block("INVALID_RECEIPT_RECORD")
            continue
        rid, receipt = item
        if (not isinstance(rid, str) or not _RECEIPT_ID.fullmatch(rid)
                or rid in seen or not isinstance(receipt, dict)):
            block("INVALID_OR_DUPLICATED_RECEIPT")
            continue
        seen.add(rid)
        if receipt.get("receipt") != rid:
            block("RECEIPT_ID_CONFLICT")
        status = receipt.get("status")
        if not isinstance(status, str) or status not in _NONAPPLIED | {_FINAL, "APPLYING"}:
            block("UNKNOWN_RECEIPT_STATUS")
            continue
        statuses[status] += 1
        names = ("total_count", "ready_count", "added_count",
                 "rejected_count", "processed_count")
        if any(type(receipt.get(name)) is not int or receipt[name] < 0
               for name in names):
            block("INVALID_RECEIPT_COUNTERS")
            continue
        total, ready, added, rejected, processed = (
            receipt[name] for name in names
        )
        if (total == 0 or ready > total or added > ready
                or processed > total or processed != added + rejected
                or receipt.get("finance_processed") is not False):
            block("INCONSISTENT_RECEIPT_COUNTERS")
            continue
        if status == _FINAL:
            if added + rejected != total or processed != total:
                block("INCOMPLETE_FINAL_RECEIPT")
            accepted[rid] = added
        elif status == "APPLYING":
            block("IMPORT_APPLY_IN_PROGRESS")
        elif added:
            block("NONAPPLIED_RECEIPT_HAS_COMMITTED_ROWS")

    seen_rows = Counter()
    if not isinstance(imported_rows, list):
        block("INVALID_COMPLETED_ROWS")
        imported_rows = []
    for row in imported_rows:
        if not isinstance(row, dict):
            block("INVALID_IMPORTED_ROW")
            continue
        rid = row.get("import_receipt")
        if not isinstance(rid, str) or rid not in accepted:
            block("ORPHANED_OR_NONFINAL_IMPORTED_ROW")
        else:
            seen_rows[rid] += 1

    for rid, expected in accepted.items():
        if seen_rows[rid] != expected:
            block("COMPLETED_RECEIPT_ROW_COUNT_MISMATCH")

    if type(report_count) is not int or report_count < 0:
        block("MISSING_REPORT_IMPORT_COUNT")
    elif report_count != len(imported_rows):
        block("REPORT_SNAPSHOT_IMPORT_COUNT_STALE")

    if not blockers and len(imported_rows):
        # The current CREDIT NOTE manifest only provides an import count,
        # not a verified import-row identity hash. Count equality alone is
        # insufficient for an approval of nonzero imported rows.
        block("NONZERO_IMPORT_ROWSET_IDENTITY_NOT_CERTIFIED")

    return {
        "result": "PASS_ZERO_IMPORTS" if not blockers else "REVIEW_REQUIRED",
        "receipt_count": len(seen),
        "receipt_status_counts": dict(sorted(statuses.items())),
        "completed_import_receipt_count": len(accepted),
        "completed_import_row_count": len(imported_rows),
        "report_import_row_count": report_count if type(report_count) is int else None,
        "blockers": blockers,
        "scope": "IMPORT_LEDGER_ONLY",
        "baseline_snapshot_freshness": "NOT_CERTIFIED",
        "financial_execution": "RESTRICTED",
        "database_writes": False,
    }


def audit_firestore_v140(db, report_manifest):
    """Read-only full receipt collection + strict source row reader.

    Raises on Firestore failures rather than manufacturing a PASS.
    Application code must not swallow partial/failed reads.
    """
    from report_api import completed_import_rows

    docs = db.collection("dashboard_import_receipts_v140").get(
        timeout=60, retry=None
    )
    if len(docs) > 20000:
        raise ValueError("Import receipt audit review limit exceeded")
    receipts = [(doc.id, doc.to_dict()) for doc in docs]
    imported_rows = completed_import_rows(db)
    return audit_import_receipts(receipts, imported_rows, report_manifest)
