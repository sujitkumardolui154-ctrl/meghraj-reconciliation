REPORTABLE_4F = REQUIRED_4F | SAFE_EXTRA_4F


class Blocked(RuntimeError):
    """Known safe diagnostic codes, not raw cloud exception details."""


def require(condition: bool, code: str) -> None:
    if not condition:
        raise Blocked(code)


class FilteredStatusOutput(io.TextIOBase):
    """Capture only exact review-approved fixed status lines, never secrets."""

    def __init__(self, destination):
        self.destination = destination
        self.pending = ""
        self.seen = set()

    def writable(self):
        return True

    def write(self, text):
        if not isinstance(text, str):
            return 0
        self.pending += text
        # Do not allow arbitrary or unbounded output in memory.
        if len(self.pending) > 16384:
            raise Blocked("QA_OPERATOR_OUTPUT_EXCEEDED_LIMIT")
        while "\n" in self.pending:
            line, self.pending = self.pending.split("\n", 1)
            if line in REPORTABLE_4F:
                self.seen.add(line)
                print(line, file=self.destination, flush=True)
        return len(text)

    def flush(self):
        self.destination.flush()


def verify_mtls_design_only():
    """No approved hostname/client-CA/certificate means NO live mTLS test."""
    src = g.PLACEHOLDER.read_text("utf-8")
    require(
        "qa-r311.example.invalid" in src
        and "mode require_and_verify" in src
        and "trust_pool file /etc/caddy/r311-approved-client-ca.pem" in src
        and "DO NOT IMPORT OR DEPLOY AS-IS" in src,
        "QA_MTLS_REFERENCE_CHANGED",
    )
    # Read-only inspection of the existing Caddy binary, not a TLS handshake
    # or a certificate path probe. Avoid logging Caddy build metadata.
    version = g.docker("exec", g.CADDY, "caddy", "version").strip()
    require(version.startswith("v2."), "QA_CADDY_NOT_VERIFIED_V2")
    require(g.caddy_preflight() == h.EXPECTED_4G_CADDY_SHA256,
            "QA_CADDY_FINGERPRINT_CHANGED")
    print("DB_R31_11_4I_MTLS_CADDY_VERSION=PASS_V2_READONLY", flush=True)
    print("DB_R31_11_4I_MTLS_REFERENCE=PASS_INVALID_HOSTNAME_DESIGN_ONLY",
          flush=True)
    print("DB_R31_11_4I_MTLS_EXTERNAL_PREREQUISITES=FQDN_CA_CERTS_APPROVAL_PENDING",
          flush=True)


